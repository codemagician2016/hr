// Storefront layout presets: 100 named designs that combine section
// variants into cohesive, industry-shaped looks. Switching presets re-skins the page;
// CMS data (services, team, about, contact) is unchanged.
//
// Architecture:
//   - Each preset has a stable `key`, a human `name`, an `aesthetic`
//     bucket (used by the picker grid grouping), a short description,
//     and a `variants` map { sectionKey: variantKey }.
//   - The storefront looks up the preset by key from
//     subscription.designPreset, then merges in any per-tenant
//     sectionVariants overrides on top.
//   - Variant key 'v1' is reserved across every section as the
//     "Classic" rendering — the look the storefront had before this
//     system existed. Layout 1 ("classic") uses v1 everywhere and is
//     the default for tenants on subscription.designPreset === null.
//
// Adding a new variant:
//   1. Build the variant component in business/app/page.js (the
//      section's variant switch handles the lookup).
//   2. Reference its key in one or more presets here.
//   3. (Optional) Update PRESET_THUMBNAILS for the picker.
//
// This package is the canonical registry. App and backend files should
// re-export it instead of copying preset data.

