const DEFAULT_PRESET_KEY = 'classic';

// Resolve which preset is active for a subscription. Callers pass the
// raw subscription object straight from the tenant API. NULL or unknown
// designPreset → "classic" (the default, current rendering).
function resolvePreset(subscription) {
  const key = subscription?.designPreset;
  if (!key) return PRESETS_BY_KEY[DEFAULT_PRESET_KEY];
  return PRESETS_BY_KEY[key] || PRESETS_BY_KEY[DEFAULT_PRESET_KEY];
}

// Resolve the variant key for a section. Order of precedence:
//   1. Per-tenant override in subscription.sectionVariants[sectionKey]
//   2. The active preset's variants[sectionKey]
//   3. 'v1' (the universal Classic fallback)
function resolveVariant(subscription, sectionKey) {
  let overrides = null;
  if (subscription?.sectionVariants) {
    if (typeof subscription.sectionVariants === 'string') {
      try { overrides = JSON.parse(subscription.sectionVariants); } catch { overrides = null; }
    } else if (typeof subscription.sectionVariants === 'object') {
      overrides = subscription.sectionVariants;
    }
  }
  if (overrides && typeof overrides[sectionKey] === 'string' && overrides[sectionKey]) {
    return overrides[sectionKey];
  }
  const preset = resolvePreset(subscription);
  return preset.variants[sectionKey] || 'v1';
}

// Convenience: resolve every section variant at once. The page.js
// rendering loop calls this once and passes individual variants down
// to each section component.
function resolveAllVariants(subscription) {
  const preset = resolvePreset(subscription);
  let overrides = {};
  if (subscription?.sectionVariants) {
    if (typeof subscription.sectionVariants === 'string') {
      try { overrides = JSON.parse(subscription.sectionVariants) || {}; } catch { overrides = {}; }
    } else if (typeof subscription.sectionVariants === 'object') {
      overrides = subscription.sectionVariants;
    }
  }
  return { ...preset.variants, ...overrides };
}


const LAYOUT_PRESET_KEYS = LAYOUT_PRESETS.map((preset) => preset.key);
const VALID_LAYOUT_PRESETS = new Set(LAYOUT_PRESET_KEYS);
const SECTION_KEYS = new Set(Object.keys(AVAILABLE_VARIANTS));

function sanitizeSectionVariants(input) {
  if (!input || typeof input !== 'object') return {};
  const out = {};
  for (const [key, value] of Object.entries(input)) {
    if (!SECTION_KEYS.has(key)) continue;
    if (typeof value !== 'string') continue;
    const trimmed = value.trim();
    if (!trimmed) continue;
    out[key] = trimmed.slice(0, 64);
  }
  return out;
}

